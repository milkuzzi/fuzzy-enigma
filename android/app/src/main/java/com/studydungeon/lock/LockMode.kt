package com.studydungeon.lock

/**
 * Режим блокировки телефона на время Фазы_Работы (Режим_Фокуса).
 *
 * Реализуется без Device Owner/ADB — на системных разрешениях, как в Focus To-do:
 * - [FULL] — полная блокировка телефона: полноэкранный оверлей поверх всех
 *   приложений («Поверх других приложений») + подавление уведомлений
 *   («Доступ к уведомлениям»). Пользователь не может уйти из приложения, открыть
 *   другое приложение или пользоваться шторкой, пока идёт Фаза_Работы.
 * - [PER_APP] — блокировка отдельных приложений: при запуске выбранного
 *   приложения показывается полноэкранный экран «Доступ запрещён» и через
 *   несколько секунд пользователь возвращается в таймер («Данные об использовании»).
 * - [NONE] — блокировка телефона отключена (поведение по умолчанию; остаётся
 *   только мягкое удержание через Screen Pinning, если оно доступно).
 */
enum class LockMode {
    NONE,
    FULL,
    PER_APP;

    companion object {
        /** Безопасный разбор имени режима из строки (для SharedPreferences). */
        fun fromName(name: String?): LockMode =
            entries.firstOrNull { it.name == name } ?: NONE
    }
}
